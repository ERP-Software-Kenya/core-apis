import { ApiPropertyOptional } from '@nestjs/swagger';
import { IsBase64, IsEmail, IsOptional, IsString, MaxLength } from 'class-validator';

export class SendQuotationEmailDto {
  @ApiPropertyOptional({ description: 'Recipient email address. If omitted, uses customer email on file.' })
  @IsEmail()
  @IsOptional()
  public recipientEmail?: string;

  @ApiPropertyOptional({ description: 'Email subject. If omitted, a default subject is generated.' })
  @IsString()
  @IsOptional()
  @MaxLength(500)
  public subject?: string;

  @ApiPropertyOptional({ description: 'Email body HTML or text. If omitted, a default quotation email is generated.' })
  @IsString()
  @IsOptional()
  @MaxLength(100000)
  public body?: string;

  @ApiPropertyOptional({ description: 'Base64-encoded PDF generated by Electron desktop client. If omitted, backend generates PDF.' })
  @IsBase64()
  @IsOptional()
  @MaxLength(20_000_000)
  public pdfBase64?: string;
}
